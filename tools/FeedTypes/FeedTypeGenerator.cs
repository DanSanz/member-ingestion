using System.Text;
using System.Text.Json;

namespace FeedTypes;

/// <summary>Turns the feed contract into the C# record for its detail lines.</summary>
public static class FeedTypeGenerator
{
    public const string ContractPath = "contracts/member-feed.json";
    public const string OutputPath = "src/MemberIngestion/Generated/MemberRecord.g.cs";

    public static string Generate(string contractJson)
    {
        using var document = JsonDocument.Parse(contractJson);
        var root = document.RootElement;
        var record = root.GetProperty("record").GetString()!;
        var fields = root.GetProperty("fields").EnumerateArray().Select(Field.From).ToList();

        var code = new StringBuilder();
        code.AppendLine("// <auto-generated>");
        code.AppendLine($"//   Generated by tools/FeedTypes from {ContractPath}. DO NOT EDIT.");
        code.AppendLine("//   To change a field, change the contract (CODEOWNERS) and run: dotnet run --project tools/FeedTypes");
        code.AppendLine("// </auto-generated>");
        code.AppendLine();
        code.AppendLine("#nullable enable");
        code.AppendLine();
        code.AppendLine("namespace MemberIngestion.Generated;");
        code.AppendLine();
        code.AppendLine($"/// <summary>{root.GetProperty("feed_type").GetString()} feed, contract {root.GetProperty("version").GetString()}. {root.GetProperty("description").GetString()}");
        code.AppendLine("/// Values are text, trimmed, as received.</summary>");
        code.AppendLine($"public sealed record {record}(");
        for (var i = 0; i < fields.Count; i++)
        {
            var separator = i < fields.Count - 1 ? "," : ")";
            code.AppendLine($"    string {fields[i].PropertyName}{separator} // {fields[i].Comment}");
        }
        code.AppendLine("{");
        code.AppendLine($"    public const string FeedType = \"{root.GetProperty("feed_type").GetString()}\";");
        code.AppendLine($"    public const string ContractVersion = \"{root.GetProperty("version").GetString()}\";");
        code.AppendLine($"    public const int FieldCount = {fields.Count};");
        code.AppendLine();
        code.AppendLine("    /// <summary>Fields that are personal data. Never log them, and never log a whole record.</summary>");
        var personal = fields.Where(f => f.Class == "personal").Select(f => $"nameof({f.PropertyName})");
        code.AppendLine($"    public static readonly IReadOnlyList<string> PersonalFields = [{string.Join(", ", personal)}];");
        code.AppendLine();
        code.AppendLine($"    public static {record} FromFields(IReadOnlyList<string> fields) => new(");
        code.AppendLine("        " + string.Join(", ", fields.Select((_, i) => $"fields[{i}]")) + ");");
        code.AppendLine("}");
        return code.ToString();
    }

    private sealed record Field(string Name, string Class, string? Format, string? Note)
    {
        public static Field From(JsonElement e) => new(
            e.GetProperty("name").GetString()!,
            e.GetProperty("class").GetString()!,
            e.TryGetProperty("format", out var format) ? format.GetString() : null,
            e.TryGetProperty("note", out var note) ? note.GetString() : null);

        public string PropertyName =>
            string.Concat(Name.Split('_').Select(part => char.ToUpperInvariant(part[0]) + part[1..]));

        public string Comment =>
            string.Join("; ", new[] { Format, Note, Class == "internal" ? null : Class }.Where(s => s is not null));
    }
}
